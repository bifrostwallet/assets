#!/bin/sh
# Write a gitignored .ops.env from Secret Manager for local operator use.
#
# Team source of truth: GCP Secret Manager (`assets-ops-config`). This file is
# only a local cache so operators get ASSET_BASE_URL / BUCKET_PREFIX without
# committing hosts into the public repo.
#
# Usage:
#   ASSETS_OPS_PROJECT=<your-gcp-project> ./yarn ops:pull-env
#   ASSETS_OPS_PROJECT=<your-gcp-project> ./yarn with:ops-config -- ./yarn upload:bucket --dry-run
#
# Prerequisites: gcloud ADC + secretAccessor on the ops secret.

set -eu

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="${ROOT}/.ops.env"

PROJECT="${ASSETS_OPS_PROJECT:-$(gcloud config get-value project 2>/dev/null || true)}"
SECRET="${ASSETS_OPS_SECRET:-assets-ops-config}"

if [ -z "${PROJECT}" ] || [ "${PROJECT}" = "(unset)" ]; then
  echo "Set ASSETS_OPS_PROJECT or: gcloud config set project <id>" >&2
  exit 1
fi

# Emit ops helpers (tsc → build/scripts/*.js) before invoking via Yarn PnP.
(
  cd "${ROOT}"
  ./yarn tsc -p tsconfig.scripts.json
)

export ASSETS_OPS_JSON
ASSETS_OPS_JSON="$(gcloud secrets versions access latest --secret="${SECRET}" --project="${PROJECT}")"
export OPS_ENV_FORMAT=dotenv

{
  echo "# Generated by ./yarn ops:pull-env — do not commit."
  echo "# Source: ${SECRET} @ ${PROJECT}. Regenerate after Secret Manager updates."
  echo
  (cd "${ROOT}" && ./yarn node build/scripts/ops-config-exports.js)
} >"${OUT}"

chmod 600 "${OUT}"
unset ASSETS_OPS_JSON OPS_ENV_FORMAT

echo "Wrote ${OUT} (gitignored). Keys:" >&2
grep -E '^[A-Za-z_][A-Za-z0-9_]*=' "${OUT}" | cut -d= -f1 | sed 's/^/  /' >&2
